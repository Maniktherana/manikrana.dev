const hockeyLine = (color: string, flat: number, end: number, start: number): Line => ({
  color,
  fill: true,
  points: Array.from({ length: 161 }, (_, index) => {
    const x = index / 160;
    const t = Math.max(0, (x - start) / (1 - start));
    const rise = Math.expm1(1.98 * t ** 1.25) / Math.expm1(1.98);
    return [x, flat + flat * x * 0.25 + (end - flat * 1.25) * rise];
  }),
});

